// Apply at generation time so runtime/custom templates receive the same editorial
// rule as factory templates, without rewriting users' stored prompt versions.
const RULE_HEADING = '# 统一日期与观点呈现规则';
const WEEKLY_REPORT_DATE_RULES = `${RULE_HEADING}
以下规则统一适用于新闻、开篇综述和观点摘录；原模板关于日期筛选、排序和提示的旧要求与下列规则不一致时，以本规则为准。保留原模板的主题范围、地域偏好、章节数量、去重与充分覆盖要求。
1. 所给素材是在报告期内搜索采集的。没有明确发生日期、仅写“近日”或没有采访时间，但有具体事实或有出处的观点，且没有明确证据显示属于期外旧事的，按与近期强相关的正常内容纳入。不能因为缺少日期而删除普通新闻或观点。
2. 在原有地域和业务分类内，明确发生在所选日期范围内的事项优先排列，日期不详的放在其后，正常叙述。不设“参考动态”分组，不加“参考动态（事件日期未载明）”“采访时间未载明”“日期不详”“时间不确定”等前缀、括注或句尾提示，也不在综述、分类导语中集中解释哪些条目没有日期。
3. 综述优先概括有明确期内日期的主要动作；没有明确日期的合格素材也可用中性事实表述概括，不必写“未能确认本期新增事项”。不得补造日期，或把采集/报道日期当作事件日期，不把日期不详事项断言为“本周新出台”“本周首次实施”。
4. 日期已知且明确发生在报告期外、没有本期新增动作的事项，必须剔除，不能因本期再次采集、政策仍有效、内容重要或放宽缺日期要求而恢复。仅写出旧日期也不等于可以把旧事独立列为重点。开篇综述和正文执行同一限制；解释某条合格新事项确有必要时，旧内容才可作为该条中的简短背景。旧政策本期出现新实施、办理进展或披露结果时，突出新动作，保留统计期间、累计、预计等限定。未来活动只按已发布的安排写明计划时间，不写成已发生。
5. 观点须有素材出处并忠于原意。明确在报告期外发表且没有本期新观点的引语，从观点摘录删除；没有明确发表/采访日期且无期外证据的，正常写“**人物或机构** 表示/认为……”，不标注时间缺失、不猜职务、不虚构引语。没有可摘录观点时简短说明，不凑数。
6. 日期不详与事实冲突不同：日期、主体、数字存在实质冲突且无法消解时，仍须保留必要的不确定性，不用删提示的方式掩盖矛盾。只输出周报正文，不输出日期审核过程。`;

function appendWeeklyReportDateReminder(prompt, { startDate, endDate }) {
  return `${String(prompt || '').trimEnd()}\n\n【出稿前必须完成的核对，不在正文展示】
本次报告期严格为 ${startDate} 至 ${endDate}（含首尾日期）。逐条核对后再输出完整正文：
1. 有明确事件日期的，先与上述起止日期比较；早于 ${startDate} 或晚于 ${endDate} 且没有期内新动作的，不独立列入重点，更不能放进“本周出台/实施”的综述。期前旧政策仅写了原日期仍不算合格本期新闻，不能借背景之名单列整条。未来已公布安排可写为计划并保留将来时间。
2. 没有明确日期或只有“近日”、且无期外证据的具体事实/观点，按近期相关内容正常保留；这是“日期未知”，不同于上条“已知期外”。缺日期不加标签、不附括注、不输出审核说明。逐事项判断，不能整篇按一个日期淘汰：不要因为文章混有旧背景，连其中有依据的新进展，以及未明确过期的独立服务事项、业务做法或观点一起删除。同一事项的重复报道只要有一篇明确给出期外发生日期，合并后就不能把它重新当作日期未知。
3. 明确期内事项在同类内优先；保留原模板要求的【江苏】等地域标识、主题范围及章节。逐条核对普通事项是否遗漏，同一事项是否跨类重复；综述不得比正文扩大时间口径。`;
}

function applyWeeklyReportEditorialRules(prompt) {
  let text = String(prompt || '');
  if (text.includes(RULE_HEADING)) return text;
  // Remove known, contradictory instructions from the live coverage-first
  // templates. Do not strip content from generated reports or source articles.
  text = text
    .replace(/^4\. 日期只有“近日”或未载明[^\n]*$/gm, '4. 日期未明确但有具体事实且无期外证据的，作为近期相关动态正常纳入，在同类有明确期内日期的事项之后排列。')
    .replace(/^5\. 综述只概括日期可确认的本期新事[^\n]*$/gm, '5. 综述优先概括有明确期内日期的主要动作，日期不详的合格素材可中性概括；不补日期、外部背景、因果或宏观趋势，不从少量素材推断行业整体状态。')
    .replaceAll('旧闻回流及参考标注', '旧闻回流及日期表述')
    .replaceAll('用1—2句话概括有日期依据的本期主要动作；参考动态不支撑“本周新增”主线。', '用1—2句话概括主要动态，有明确期内日期的优先，不将日期不详事项断言为本周新增。')
    .replaceAll('旧引语不作为当周新观点；日期未明的标明时间不确定性。', '明确期外的旧引语不列入观点摘录；日期未明且无期外证据的观点正常呈现，不附时间提示。')
    .replaceAll('日期未明的具体参考做法按前述规则后排标注时间不确定性', '日期未明且无期外证据的具体做法在同类期内事项之后正常呈现');
  return `${text.trimEnd()}\n\n${WEEKLY_REPORT_DATE_RULES}`;
}

module.exports = { applyWeeklyReportEditorialRules, appendWeeklyReportDateReminder, WEEKLY_REPORT_DATE_RULES };
